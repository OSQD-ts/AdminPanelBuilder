/**
 * Writes the component kit's rules the panel uses into `src/render/kit-css.generated.ts`.
 *
 * The page is drawn with `@osqd/ui`'s components (see src/client/kit.ts), and this library has no
 * runtime dependencies, so the kit is a devDependency read here, at build time, the way the client
 * is bundled by scripts/build-client.mjs: the output is committed, a fresh checkout serves a panel
 * without a generate step, and `--check` exits 1 when the committed copy no longer matches what
 * the installed kit and the panel's sources produce.
 *
 * Only the rules the panel needs travel (scripts/kit-css.mjs): the kit classes written anywhere in
 * src/client/, src/render/ and src/element/ decide, so a class added in the client brings its rules
 * with it on the next build. The kit's theme files are not read at all — the panel's themes supply
 * every `--oq-*` value (src/themes/kit-bridge.ts).
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { kitClassesIn, pruneKitCss } from "./kit-css.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const target = join(root, "src", "render", "kit-css.generated.ts");
const kitRoot = dirname(createRequire(import.meta.url).resolve("@osqd/ui/package.json"));
const kitVersion = JSON.parse(await readFile(join(kitRoot, "package.json"), "utf8")).version;

/** The kit's stylesheets the panel draws from, in the kit's own order. Not tokens.css: see above. */
const SHEETS = ["base.css", "components.css", "charts.css", "data.css"];

async function sources(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await sources(path)));
    else if (entry.name.endsWith(".ts") && !entry.name.endsWith(".generated.ts")) out.push(path);
  }
  return out;
}

const used = new Set();
for (const dir of ["client", "render", "element"]) {
  for (const file of await sources(join(root, "src", dir))) for (const name of kitClassesIn(await readFile(file, "utf8"))) used.add(name);
}

let css = "";
for (const sheet of SHEETS) css += pruneKitCss(await readFile(join(kitRoot, "styles", sheet), "utf8"), used);
if (css.includes("</") || css.includes("<!--")) throw new Error("The kit's rules contain </ or <!--, which would end the <style> element the page serves them in.");

const contents = `/**
 * Generated by \`node scripts/build-kit-css.mjs\` from @osqd/ui ${kitVersion}. Do not edit.
 *
 * The component kit's rules the panel's markup uses (${used.size} kit classes), served before the
 * layout stylesheet so the panel's own rules win ties. See scripts/build-kit-css.mjs.
 */

export const KIT_VERSION = ${JSON.stringify(kitVersion)};

export const KIT_CSS = ${JSON.stringify(css)};
`;

const existing = await readFile(target, "utf8").catch(() => "");
const name = relative(root, target);
if (process.argv.includes("--check")) {
  if (existing !== contents) {
    console.error(`${name} is out of date. Run \`node scripts/build-kit-css.mjs\`.`);
    process.exit(1);
  }
  console.log(`${name} is up to date`);
} else if (existing === contents) {
  console.log(`${name} unchanged (${(css.length / 1024).toFixed(1)} kB of kit CSS)`);
} else {
  await writeFile(target, contents);
  console.log(`${name} written (${(css.length / 1024).toFixed(1)} kB of kit CSS, ${used.size} classes)`);
}
