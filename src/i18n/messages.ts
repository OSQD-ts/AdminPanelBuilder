/**
 * Every language the page ships. To add one, copy `ENGLISH`, translate every value, and add it
 * here: `Messages` makes a missing key a type error, and tests/i18n.test.ts checks every
 * placeholder survives translation.
 */
export const LOCALES: Readonly<Record<string, Messages>> = Object.freeze({ en: ENGLISH, pl: POLISH, de: GERMAN });

/** Fills `{name}` placeholders. */
export function format(template: string, values: Record<string, string | number> = {}): string {
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => (Object.hasOwn(values, name) ? String(values[name]) : whole));
}
